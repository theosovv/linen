#[path = "../test-support/reference/generator.rs"]
mod generator;

use linen::bytecode::{verify, verify_origins};
use linen::ir::{self, NodeOp};
use linen::vm::Vm;
use linen::{CompileConfig, CompileSession, RenderConfig, compile, compile_with_config, create_vm};

fn render(program: &linen::CompiledProgram, partitions: &[usize]) -> Vec<f32> {
    let mut vm = create_vm(program).expect("generated bytecode must create a VM");
    let count = program.typed.render.render_samples as usize;
    let mut output = Vec::with_capacity(count);
    let mut scratch = vec![0.0; program.config.block_size];
    let mut index = 0;

    while output.len() < count {
        let length = partitions[index % partitions.len()].min(count - output.len());
        vm.render_into(&mut scratch[..length])
            .expect("generated finite programs must render");
        output.extend_from_slice(&scratch[..length]);
        index += 1;
    }
    output
}

fn assert_close(actual: f32, expected: f32, sample_index: usize) {
    let tolerance = 2e-5 + 2e-5 * expected.abs();
    assert!(
        (actual - expected).abs() <= tolerance,
        "sample {sample_index}: actual {actual}, expected {expected}, tolerance {tolerance}"
    );
}

#[test]
fn spec_7_6_codegen_verifier_accepts_every_generated_valid_program() {
    for seed in 0..32 {
        let source = generator::program(seed);
        let first = compile(&source, RenderConfig::default())
            .expect("the default config is valid")
            .result
            .expect("generated source must compile");
        let second = compile_with_config(
            "logical.ln",
            &source,
            CompileConfig::default(),
            RenderConfig::default(),
        )
        .expect("the default config is valid")
        .result
        .expect("repeated generated source must compile");

        assert_eq!(first, second);
        verify(&first.bytecode).expect("generated bytecode must verify");
        let outcome =
            compile(&source, RenderConfig::default()).expect("the default config is valid");
        let program = outcome
            .result
            .as_ref()
            .expect("generated source must compile");
        ir::verify(&program.ir, &outcome.sources).expect("generated IR must verify");
        verify_origins(&program.bytecode, &outcome.sources).expect("generated origins must verify");
        assert!(
            program
                .ir
                .nodes
                .iter()
                .any(|node| matches!(node.op, NodeOp::Sine(_)))
        );
    }
}

#[test]
fn spec_7_6_generated_block_partition_does_not_change_output() {
    let partitions = [1, 2, 7, 3, 16, 5, 1];
    for seed in 0..16 {
        let source = generator::program(seed);
        let whole = compile(&source, RenderConfig::default())
            .expect("the default config is valid")
            .result
            .expect("generated source must compile");
        let partitioned = compile(
            &source,
            RenderConfig {
                block_size: 16,
                ..RenderConfig::default()
            },
        )
        .expect("the partition config is valid")
        .result
        .expect("generated source must compile");
        let expected = render(&whole, &[whole.config.block_size]);
        let actual = render(&partitioned, &partitions);

        assert_eq!(actual.len(), expected.len());
        for (index, (actual, expected)) in actual.iter().zip(&expected).enumerate() {
            assert_close(*actual, *expected, index);
        }
    }
}

#[test]
fn spec_7_6_pure_arithmetic_block_partitions_are_bit_exact() {
    let source = "let value = 1 + 2 * 3; let out = -value / 7; render 1ms;";
    let whole = compile(source, RenderConfig::default())
        .expect("the default config is valid")
        .result
        .expect("the arithmetic source must compile");
    let partitioned = compile(
        source,
        RenderConfig {
            block_size: 3,
            ..RenderConfig::default()
        },
    )
    .expect("the partition config is valid")
    .result
    .expect("the arithmetic source must compile");

    assert_eq!(render(&whole, &[128]), render(&partitioned, &[1, 2, 3]));
}

#[test]
fn spec_7_6_session_local_source_id_does_not_change_execution_artifacts() {
    let source = generator::program(42);
    let simple = compile(&source, RenderConfig::default())
        .expect("the default config is valid")
        .result
        .expect("the generated source must compile");
    let mut session = CompileSession::new(CompileConfig::default());
    session
        .sources_mut()
        .add_source("dummy.ln", "let out = 0; render 1ms;");
    let source_id = session.sources_mut().add_source("actual.ln", &source);
    let shifted = session
        .compile(source_id, RenderConfig::default())
        .expect("the source belongs to the session")
        .expect("the shifted source must compile");

    assert_eq!(simple.ir.nodes.len(), shifted.ir.nodes.len());
    assert_eq!(simple.bytecode.instructions, shifted.bytecode.instructions);
    assert_eq!(simple.bytecode.output, shifted.bytecode.output);
    let expected = render(&simple, &[128]);
    let actual = render(&shifted, &[1, 7, 2, 128, 3]);
    for (index, (actual, expected)) in actual.iter().zip(&expected).enumerate() {
        assert_close(*actual, *expected, index);
    }
}

#[test]
fn spec_7_6_reset_property_holds_for_generated_programs() {
    for seed in 0..8 {
        let source = generator::program(seed);
        let program = compile(&source, RenderConfig::default())
            .expect("the default config is valid")
            .result
            .expect("generated source must compile");
        let mut vm = Vm::new(
            &program.bytecode,
            linen::vm::VmConfig {
                sample_rate: 48_000,
                block_size: 48,
            },
        )
        .expect("generated bytecode must create a VM");
        let mut first = vec![0.0; 48];
        vm.render_into(&mut first).expect("first render must work");
        vm.reset();
        let mut second = vec![0.0; 48];
        vm.render_into(&mut second).expect("reset render must work");

        for (index, (actual, expected)) in second.iter().zip(&first).enumerate() {
            assert_eq!(actual.to_bits(), expected.to_bits(), "sample {index}");
        }
    }
}
